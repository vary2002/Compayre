export interface DirectorInfo {
  // Identity
  name: string;
  din: string;
  designation: string;
  directorCategory?: string;
  qualification?: string;
  dateOfBirth?: string;
  promoterStatus?: string;
  gender?: string;
  appointmentDate?: string;
  role?: string;
  // Per-year remuneration
  year: number;
  compensation: string;                 // Total Remuneration (Year X Total Remuneration)
  salary?: string;                      // Basic Salary (Year X Basic Salary)
  bonus?: string;                       // Bonus / Commission (Year X Bonus / Commission)
  perquisites?: string;                 // Perquisites / Allowances (Year X Perquisites/Allowances)
  retirementBenefits?: string;          // PF / Retirement (Year X PF/Retirement)
  payExcludingEsops?: string;           // Total Pay excluding ESOPs (Year X Pay (Excl ESOPs))
  esopsExercised?: number;              // Number of ESOPs exercised (Year X ESOPS)
  // Options
  optionsGranted?: number;              // Options Granted (Year X Options Granted)
  optionDiscount?: string;              // Discount on Options (Year X Discount)
  esopFairValue?: string;               // Fair Value of Options (Year X Fair Value)
  optionsAggregateValue?: string;       // Aggregate Value of Options (Year X Aggregate Value)
  esopMarketValue?: string;             // Market value of ESOPs as a compensation component
  // Metadata
  comments?: string;                    // Year Comments (Year X Comments)
  remunerationStatus?: string;          // Remuneration Status (Year X Remuneration Status)
  // Company financials — same value for all directors of the same company + year
  sector?: string;
  industry?: string;
  totalIncome?: string;                 // Total Income e.g. "₹7,00,000 Cr"
  profitAfterTax?: string;              // PAT e.g. "₹55,000 Cr"
  returnOnAssets?: string;              // ROA e.g. "9.0%"
  employeeCost?: string;                // Employee Cost e.g. "₹26,000 Cr"
  companyMarketCap?: string;            // Market Cap e.g. "₹17,85,234 Cr"
  // Governance
  salaryToMedianEmployeeRatio?: string; // Salary to Median Employee Pay ratio (Key: Salary to med emp pay)
  peerCompensations?: string[];         // Peer director total compensation values (Peer 1–5 Comp)
}

